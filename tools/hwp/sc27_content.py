def days(v):
    return (v[1] - v[0]).days + 1


def plan_rows(plan):
    rows = [['차수', '대 상', '원서접수', '서류심사', '합격자 발표', '등 록']]
    for 차, 대상, 접수, 심사, 발표, 등록 in plan:
        yr = 접수[0].year != 2026
        rows.append([차, 대상,
                     ('%s(%s)' % (rng(접수, yr), '%d일' % days(접수))),
                     rng(심사, 심사[0].year != 2026),
                     one(발표, 발표.year != 2026) + '(%s)' % wd(발표),
                     rng(등록, 등록[0].year != 2026)])
    return rows


