def rng(v, yr=False):
    a, b = v
    head = ("'%02d. " % (a.year % 100)) if yr else ''
    tail = ("'%02d. " % (b.year % 100)) if b.year != a.year else ''
    return '%s%s ∼ %s%s' % (head, md(a), tail, md(b))


def one(d, yr=False):
    return ('%s%s' % (("'%02d. " % (d.year % 100)) if yr else '', md(d)))


