def shift(v, dt):
    if isinstance(v, tuple):
        return (v[0] + dt, v[1] + dt)
    return v + dt


def conv(src, dt):
    out = {k: shift(v, dt) for k, v in src.items()}
    for k, v in out.items():                      # 요일이 보존됐는지 확인
        a, b = (v if isinstance(v, tuple) else (v, v))
        assert wd(a) == wd(shift(src[k], timedelta(0))[0] if isinstance(src[k], tuple)
                           else src[k]), k
    return out


