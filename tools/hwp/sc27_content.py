def wd(d):
    return W[d.weekday()]


def md(d):
    return '%d. %d.' % (d.month, d.day)


def mdw(d):
    return '%d. %d.(%s)' % (d.month, d.day, wd(d))


def ymdw(d):
    return '%d. %d. %d.(%s)' % (d.year, d.month, d.day, wd(d))


