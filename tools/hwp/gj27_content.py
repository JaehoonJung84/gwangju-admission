def dw(d):
    """10. 19.(월) — 해가 2027이면 '27. 을 앞에 붙인다."""
    s = '%d. %d.(%s)' % (d.month, d.day, W[d.weekday()])
    return ("'27. " + s) if d.year == 2027 else s


def span(a, b):
    return dw(a) + '∼' + dw(b)


def days(rounds):
    return sum((b - a).days + 1 for a, b in rounds)


