def onew(d):                        # 5. 27.(수)
    return '%s(%s)' % (md(d), wd(d))


def onewy(d):                       # '27. 1. 6.(수)
    return "'%02d. %s(%s)" % (d.year % 100, md(d), wd(d))


def rngw(v, yr=False):              # 1. 11.(월)∼1. 15.(금)
    a, b = v
    head = ("'%02d. " % (a.year % 100)) if yr else ''
    tail = ("'%02d. " % (b.year % 100)) if b.year != a.year else ''
    return '%s%s∼%s%s' % (head, onew(a), tail, onew(b))


def plan_rows(plan):
    rows = [['차수', '원서접수', '합격자 발표', '등록금 납부']]
    for 차, _, 접수, 심사, 발표, 등록 in plan:
        rows.append([차,
                     rngc(접수, 접수[0].year != 2026) + ' (%d일)' % days(접수),
                     one(발표, 발표.year != 2026) + '(%s)' % wd(발표),
                     rngw(등록, 등록[0].year != 2026)])
    return rows


def judge(plan):
    return ' / '.join('%s %s' % (p[0], rng(p[3], p[3][0].year != 2026)) for p in plan)


